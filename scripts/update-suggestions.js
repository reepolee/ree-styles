const registry_url = "https://registry.npmjs.org/tailwindcss/latest";

function read_requested_version() {
	const version_index = Bun.argv.indexOf("--version");
	if (version_index === -1) {
		return undefined;
	}

	return Bun.argv[version_index + 1];
}

async function fetch_text(url) {
	const response = await fetch(url);
	if (!response.ok) {
		throw new Error(`Request failed with ${response.status}: ${url}`);
	}

	return response.text();
}

function parse_theme_values(theme_css, variable_pattern) {
	const values = {};
	let variable_match = variable_pattern.exec(theme_css);

	while (variable_match) {
		const normalized_value = variable_match[2].replace(/\s+/g, " ");
		values[variable_match[1]] = normalized_value.trim();
		variable_match = variable_pattern.exec(theme_css);
	}

	return values;
}

const requested_version = read_requested_version();
let tailwind_version = requested_version;

if (!tailwind_version) {
	const registry_text = await fetch_text(registry_url);
	const registry_data = JSON.parse(registry_text);
	tailwind_version = registry_data.version;
}

if (!/^\d+\.\d+\.\d+(?:-[\w.-]+)?$/.test(tailwind_version)) {
	throw new Error(`Invalid Tailwind version: ${tailwind_version}`);
}

const theme_url = `https://unpkg.com/tailwindcss@${tailwind_version}/theme.css`;
const theme_css = await fetch_text(theme_url);
const theme_colors = parse_theme_values(theme_css, /--color-([\w-]+):\s*([^;]+);/g);
if (Object.keys(theme_colors).length === 0) {
	throw new Error(`No color tokens found in ${theme_url}`);
}

const theme_font_families = parse_theme_values(theme_css, /--font-(?!weight-)([\w-]+):\s*([^;]+);/g);
const theme_font_sizes = {};
const raw_font_sizes = parse_theme_values(theme_css, /--text-(?!shadow-)([\w-]+):\s*([^;]+);/g);
for (const [token_name, token_value] of Object.entries(raw_font_sizes)) {
	if (token_name.endsWith("--line-height")) {
		continue;
	}

	const line_height_name = `${token_name}--line-height`;
	theme_font_sizes[token_name] = {
		font_size: token_value,
		line_height: raw_font_sizes[line_height_name],
	};
}

if (Object.keys(theme_font_families).length === 0 || Object.keys(theme_font_sizes).length === 0) {
	throw new Error(`No typography tokens found in ${theme_url}`);
}

const generated_header = "// Generated by scripts/update-suggestions.js. Do not edit manually.";
const generated_colors = JSON.stringify(theme_colors, null, "\t");
const generated_font_families = JSON.stringify(theme_font_families, null, "\t");
const generated_font_sizes = JSON.stringify(theme_font_sizes, null, "\t");
const generated_source = `${generated_header}\nexport const tailwind_version = ${JSON.stringify(tailwind_version)};\nexport const theme_colors = ${generated_colors};\nexport const theme_font_families = ${generated_font_families};\nexport const theme_font_sizes = ${generated_font_sizes};\n`;
await Bun.write("src/generated-theme.js", generated_source);
console.log(`Updated theme colors and typography from Tailwind CSS ${tailwind_version}.`);
